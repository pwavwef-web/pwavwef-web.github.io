import {
  chunkSegments,
  flattenScript,
  passageSynthesisInput,
  spokenPassages,
  type DirectedSegment,
  type FlatPassage,
  type NarratorClipDoc,
  type NarratorEditionDoc,
  type PronunciationEntry,
} from '@az-studio/shared';

/**
 * What a generation request will actually do for an edition. Pure, so the API, the worker and the tests
 * agree: passages whose selected take already matches their current inputs are skipped; a ready take made
 * from the same inputs is reused (no new charge); passages in an active job are not submitted twice.
 */

export type Scope = 'selection' | 'passages' | 'section' | 'edition' | 'preview';

export interface PlannedItem {
  /** passageId, 'preview' for a selection preview, or pv-{variant}-{passageId} for a passage preview. */
  key: string;
  passageId: string | null;
  /** A listening preview of this passage (never becomes a take). */
  previewOf?: string | null;
  variant?: 'directed' | 'undirected' | null;
  text: string;
  providerText: string;
  style: string;
  inputHash: string;
  /** One request per chunk; each chunk is one or more styled text blocks. */
  chunks: DirectedSegment[][];
  pronunciations: { term: string; spokenAs: string }[];
}

export interface NarrationPlan {
  items: PlannedItem[];
  /** Passages whose existing ready take with identical inputs becomes the selected take instead. */
  reuse: { passageId: string; clipId: string }[];
  skipped: { passageId: string; reason: string }[];
}

type Clip = NarratorClipDoc & { id: string };

export function targetPassages(edition: Pick<NarratorEditionDoc, 'script' | 'settings'>, scope: Exclude<Scope, 'preview'>, opts: { passageIds?: string[]; sectionId?: string | null }): FlatPassage[] {
  const spoken = spokenPassages(edition.script, edition.settings.includeClosing);
  if (scope === 'edition') return spoken;
  if (scope === 'section') return spoken.filter((f) => f.sectionId === opts.sectionId);
  if (scope === 'passages') {
    const want = new Set(opts.passageIds ?? []);
    return spoken.filter((f) => want.has(f.passage.id));
  }
  return [];
}

export function planNarration(input: {
  edition: Pick<NarratorEditionDoc, 'script' | 'settings' | 'takes' | 'directions'>;
  clips: Clip[];
  notebook: readonly PronunciationEntry[];
  voice: { id: string; modelId: string };
  scope: Scope;
  variant?: 'directed' | 'undirected';
  passageIds?: string[];
  sectionId?: string | null;
  selection?: string;
  force: boolean;
  /** Passage ids already being generated by an active job. */
  inFlight: ReadonlySet<string>;
}): NarrationPlan {
  const { edition, clips, notebook, voice } = input;
  const items: PlannedItem[] = [];
  const reuse: NarrationPlan['reuse'] = [];
  const skipped: NarrationPlan['skipped'] = [];
  if (input.scope === 'selection') {
    const text = (input.selection ?? '').trim();
    if (text) {
      const s = passageSynthesisInput({ id: 'preview', kind: 'paragraph', text, source: '' }, edition.settings, notebook, voice);
      items.push({ key: 'preview', passageId: null, text, providerText: s.providerText, style: s.style, inputHash: s.inputHash, chunks: chunkSegments(s.segments), pronunciations: s.applied.map((a) => ({ term: a.term, spokenAs: a.spokenAs })) });
    }
    return { items, reuse, skipped };
  }
  if (input.scope === 'preview') {
    const pid = input.passageIds?.[0];
    const f = pid ? targetPassages(edition, 'passages', { passageIds: [pid] })[0] : undefined;
    if (!f) return { items, reuse, skipped };
    const variant = input.variant ?? 'directed';
    const s = passageSynthesisInput(f.passage, edition.settings, notebook, voice, variant === 'directed' ? (edition.directions ?? []) : []);
    if (clips.some((c) => c.passageId === previewClipKey(variant, f.passage.id) && c.status === 'ready' && c.inputHash === s.inputHash)) {
      skipped.push({ passageId: f.passage.id, reason: 'this preview already exists' });
      return { items, reuse, skipped };
    }
    items.push({ key: `pv-${variant}-${f.passage.id}`, passageId: null, previewOf: f.passage.id, variant, text: f.passage.text, providerText: s.providerText, style: s.style, inputHash: s.inputHash, chunks: chunkSegments(s.segments), pronunciations: s.applied.map((a) => ({ term: a.term, spokenAs: a.spokenAs })) });
    return { items, reuse, skipped };
  }
  const byId = new Map(clips.map((c) => [c.id, c]));
  for (const f of targetPassages(edition, input.scope, input)) {
    const p = f.passage;
    if (input.inFlight.has(p.id)) {
      skipped.push({ passageId: p.id, reason: 'already being generated' });
      continue;
    }
    const s = passageSynthesisInput(p, edition.settings, notebook, voice, edition.directions ?? []);
    const selected = byId.get(edition.takes[p.id] ?? '');
    if (!input.force && selected && selected.status === 'ready' && selected.inputHash === s.inputHash) {
      skipped.push({ passageId: p.id, reason: 'audio is current' });
      continue;
    }
    if (!input.force) {
      const same = clips.filter((c) => c.passageId === p.id && c.status === 'ready' && c.inputHash === s.inputHash).sort((a, b) => b.version - a.version)[0];
      if (same) {
        reuse.push({ passageId: p.id, clipId: same.id });
        continue;
      }
    }
    items.push({ key: p.id, passageId: p.id, text: p.text, providerText: s.providerText, style: s.style, inputHash: s.inputHash, chunks: chunkSegments(s.segments), pronunciations: s.applied.map((a) => ({ term: a.term, spokenAs: a.spokenAs })) });
  }
  return { items, reuse, skipped };
}

export interface ExportPart {
  passageId: string;
  clipId: string;
  inputHash: string;
  sectionId: string | null;
  sectionTitle: string | null;
  kind: FlatPassage['passage']['kind'];
}

/**
 * The parts of an export, in narration order. Every spoken passage needs a selected, ready take made from its
 * current inputs — otherwise the export is refused and the passages are listed (stale audio never slips in).
 */
export function planExport(input: { edition: Pick<NarratorEditionDoc, 'script' | 'settings' | 'takes' | 'directions'>; clips: Clip[]; notebook: readonly PronunciationEntry[]; voice: { id: string; modelId: string } }): { parts: ExportPart[]; missing: string[]; stale: string[] } {
  const byId = new Map(input.clips.map((c) => [c.id, c]));
  const parts: ExportPart[] = [];
  const missing: string[] = [];
  const stale: string[] = [];
  for (const f of flattenScript(input.edition.script, input.edition.settings.includeClosing)) {
    const p = f.passage;
    if (p.skip || !p.text.trim()) continue;
    const s = passageSynthesisInput(p, input.edition.settings, input.notebook, input.voice, input.edition.directions ?? []);
    const clip = byId.get(input.edition.takes[p.id] ?? '');
    if (!clip || clip.status !== 'ready' || !clip.storagePath) missing.push(p.id);
    else if (clip.inputHash !== s.inputHash) stale.push(p.id);
    else parts.push({ passageId: p.id, clipId: clip.id, inputHash: clip.inputHash, sectionId: f.sectionId, sectionTitle: f.sectionTitle, kind: p.kind });
  }
  return { parts, missing, stale };
}

/** Clip key of a passage listening preview (kept apart from takes). */
export const previewClipKey = (variant: 'directed' | 'undirected', passageId: string) => `preview-${variant}-${passageId}`;
