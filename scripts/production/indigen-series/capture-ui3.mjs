import { chromium } from 'playwright-core';
import path from 'node:path';
const BASE = 'http://localhost:5199';
const OUT = path.resolve('exports/indigen-contributor-series/_work/ui');
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, locale: 'en-GB' });
const page = await ctx.newPage();
const shot = async (n) => { await page.waitForTimeout(600); await page.screenshot({ path: path.join(OUT, `${n}.png`) }); console.log('saved', n); };
await page.goto(BASE + '/contributor/preview/activity', { waitUntil: 'domcontentloaded' });
await page.getByText(/contributor portal/i).first().waitFor({ timeout: 45000 });
await page.waitForTimeout(1500);
await page.getByRole('button', { name: /Review decisions/i }).first().click().catch(async () => { await page.getByText(/Review decisions/i).first().click(); });
await page.waitForTimeout(800);
await page.evaluate(() => { const els = [document.scrollingElement, ...document.querySelectorAll('*')].filter((e) => e && e.scrollHeight > e.clientHeight + 50 && getComputedStyle(e).overflowY !== 'hidden'); (els[els.length - 1]).scrollBy(0, 420); });
await shot('activity-decisions');
// submit button state: tick the permission box on e8 and capture
await page.goto(BASE + '/contributor/preview/assignment/everyday?item=e8', { waitUntil: 'domcontentloaded' });
await page.getByText(/expression 8 of 8/i).first().waitFor({ timeout: 45000 });
await page.getByPlaceholder(/Write the Kasem the way you would say it/i).fill('[Sample Kasem translation]');
await page.getByText(/Alternatives and usage note/i).first().click();
await page.getByPlaceholder(/Who says this, to whom/i).fill('Said to a friend or neighbour who is about to travel. Warm and everyday, not formal.');
await page.getByRole('checkbox').first().check();
await page.waitForTimeout(800);
await shot('e8-ready');
await page.getByRole('button', { name: /Submit for review/i }).first().click();
await page.waitForTimeout(1500);
await shot('e8-confirm');
await page.waitForTimeout(1500);
await shot('e8-confirm2');
await browser.close();
